% 子函数2：模型性能指标
% ========================================================================
function metrics = prediction_metrics(actual_age, predicted_age)

    valid = ~isnan(actual_age) & ~isnan(predicted_age);
    actual_age = actual_age(valid);
    predicted_age = predicted_age(valid);

    metrics.N = numel(actual_age);

    if metrics.N < 2
        metrics.R = NaN;
        metrics.MAE = NaN;
        metrics.RMSE = NaN;
        metrics.R2 = NaN;
        return;
    end

    metrics.R = corr(actual_age, predicted_age, 'Type', 'Pearson');
    metrics.MAE = mean(abs(predicted_age - actual_age));
    metrics.RMSE = sqrt(mean((predicted_age - actual_age).^2));

    ss_res = sum((actual_age - predicted_age).^2);
    ss_tot = sum((actual_age - mean(actual_age)).^2);

    if ss_tot == 0
        metrics.R2 = NaN;
    else
        metrics.R2 = 1 - ss_res / ss_tot;
    end
end

