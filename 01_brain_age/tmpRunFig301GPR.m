%% ========================================================================
% 子函数4：三组小提琴图
% ========================================================================
function violinplot_with_box(data, groupLabels, colors)

    nGroups = numel(data);
    maxWidth = 0.4;
    boxWidth = 0.2;

    hold on;

    for g = 1:nGroups

        d = data{g}(:);
        d = d(~isnan(d));

        if isempty(d)
            continue;
        end

        [f, xi] = ksdensity(d);
        f_norm = f / max(f) * maxWidth;

        x_left = g - f_norm;
        x_right = g + f_norm;

        x_poly = [x_left, fliplr(x_right)];
        y_poly = [xi, fliplr(xi)];

        fill( ...
            x_poly, ...
            y_poly, ...
            colors{g}, ...
            'FaceAlpha', 0.4, ...
            'EdgeColor', 'none' ...
        );

        q1 = prctile(d, 25);
        q3 = prctile(d, 75);
        median_value = median(d);
        iqr_value = q3 - q1;

        lower_whisker = max(min(d), q1 - 1.5 * iqr_value);
        upper_whisker = min(max(d), q3 + 1.5 * iqr_value);

        box_x = [ ...
            g - boxWidth / 2, ...
            g + boxWidth / 2, ...
            g + boxWidth / 2, ...
            g - boxWidth / 2 ...
        ];

        box_y = [q1, q1, q3, q3];

        patch( ...
            box_x, ...
            box_y, ...
            'w', ...
            'EdgeColor', 'k', ...
            'LineWidth', 1.5, ...
            'FaceColor', 'w' ...
        );

        line( ...
            [g - boxWidth / 2, g + boxWidth / 2], ...
            [median_value, median_value], ...
            'Color', 'k', ...
            'LineWidth', 2 ...
        );

        line( ...
            [g, g], ...
            [lower_whisker, q1], ...
            'Color', 'k', ...
            'LineWidth', 1 ...
        );

        line( ...
            [g, g], ...
            [q3, upper_whisker], ...
            'Color', 'k', ...
            'LineWidth', 1 ...
        );

        line( ...
            [g - boxWidth / 4, g + boxWidth / 4], ...
            [lower_whisker, lower_whisker], ...
            'Color', 'k', ...
            'LineWidth', 1 ...
        );

        line( ...
            [g - boxWidth / 4, g + boxWidth / 4], ...
            [upper_whisker, upper_whisker], ...
            'Color', 'k', ...
            'LineWidth', 1 ...
        );

        outliers = d(d < lower_whisker | d > upper_whisker);

        if ~isempty(outliers)
            scatter( ...
                g * ones(size(outliers)), ...
                outliers, ...
                10, ...
                'k', ...
                'filled', ...
                'MarkerFaceAlpha', 0.5 ...
            );
        end
    end

    xticks(1:nGroups);
    xticklabels(groupLabels);
    xlim([0.5, nGroups + 0.5]);

    hold off;
end

%% ========================================================================
% 子函数5：Holm多重比较校正
% ========================================================================
function adjusted_p = holm_adjust(raw_p)

    raw_p = raw_p(:);
    adjusted_p = nan(size(raw_p));

    valid = ~isnan(raw_p);
    p = raw_p(valid);

    if isempty(p)
        return;
    end

    [p_sorted, sort_idx] = sort(p, 'ascend');
    m = numel(p_sorted);

    adjusted_sorted = (m - (1:m)' + 1) .* p_sorted;
    adjusted_sorted = cummax(adjusted_sorted);
    adjusted_sorted = min(adjusted_sorted, 1);

    adjusted_unsorted = nan(m, 1);
    adjusted_unsorted(sort_idx) = adjusted_sorted;

    adjusted_p(valid) = adjusted_unsorted;
end
