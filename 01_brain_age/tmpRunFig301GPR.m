% 子函数1：通过交叉验证选择岭回归lambda
% ========================================================================
function best_lambda = select_best_lambda(X, y, lambda_list, kfold, seed)

    rng(seed);

    n = size(X, 1);
    kfold = min(kfold, n);

    if kfold < 2
        error('用于选择lambda的样本量过少。');
    end

    cvp = cvpartition(n, 'KFold', kfold);
    cv_mse = nan(numel(lambda_list), 1);

    for i = 1:numel(lambda_list)

        current_lambda = lambda_list(i);
        fold_mse = nan(cvp.NumTestSets, 1);

        for fold = 1:cvp.NumTestSets

            train_idx = cvp.training(fold);
            test_idx = cvp.test(fold);

            X_train = X(train_idx, :);
            y_train = y(train_idx);

            X_test = X(test_idx, :);
            y_test = y(test_idx);

            mu = mean(X_train, 1);
            sigma = std(X_train, 0, 1);
            sigma(sigma == 0) = 1;

            X_train_std = (X_train - mu) ./ sigma;
            X_test_std = (X_test - mu) ./ sigma;

            model = fitrlinear( ...
                X_train_std, ...
                y_train, ...
                'Learner', 'leastsquares', ...
                'Regularization', 'ridge', ...
                'Lambda', current_lambda ...
            );

            pred = predict(model, X_test_std);
            fold_mse(fold) = mean((y_test - pred).^2);
        end

        cv_mse(i) = mean(fold_mse, 'omitnan');
    end

    [~, best_idx] = min(cv_mse);
    best_lambda = lambda_list(best_idx);
end

