%% ========================= 13. 三组总体差异及总体效应量 =========================
all_pad = [pad_sub1(:); pad_sub2(:); pad_tdc(:)];

group_code = [ ...
    ones(numel(pad_sub1), 1); ...
    2 * ones(numel(pad_sub2), 1); ...
    3 * ones(numel(pad_tdc), 1) ...
];

grand_mean = mean(all_pad);
group_means = [mean(pad_sub1); mean(pad_sub2); mean(pad_tdc)];
group_ns = [numel(pad_sub1); numel(pad_sub2); numel(pad_tdc)];

ss_between = sum(group_ns .* (group_means - grand_mean).^2);

ss_within = ...
    sum((pad_sub1 - mean(pad_sub1)).^2) + ...
    sum((pad_sub2 - mean(pad_sub2)).^2) + ...
    sum((pad_tdc - mean(pad_tdc)).^2);

ss_total = ss_between + ss_within;

df_between = n_groups - 1;
df_within = numel(all_pad) - n_groups;

ms_between = ss_between / df_between;
ms_within = ss_within / df_within;

F_value = ms_between / ms_within;
P_overall = 1 - fcdf(F_value, df_between, df_within);

eta_squared = ss_between / ss_total;
partial_eta_squared = eta_squared;

omega_squared = ...
    (ss_between - df_between * ms_within) / ...
    (ss_total + ms_within);

omega_squared = max(omega_squared, 0);

overall_table = table( ...
    F_value, ...
    df_between, ...
    df_within, ...
    P_overall, ...
    eta_squared, ...
    partial_eta_squared, ...
    omega_squared, ...
    'VariableNames', { ...
        'F_Value', ...
        'DF_Between', ...
        'DF_Within', ...
        'P_Value', ...
        'Eta_Squared', ...
        'Partial_Eta_Squared', ...
        'Omega_Squared' ...
    } ...
);

disp('三组总体比较：');
disp(overall_table);

%% ========================= 14. 两两比较与效应量 =========================
pair_index = [
    1, 2;
    1, 3;
    2, 3
];

comparison_names = {
    'Subtype 1 vs Subtype 2';
    'Subtype 1 vs TDC';
    'Subtype 2 vs TDC'
};

n_comparisons = size(pair_index, 1);

N_Group1 = zeros(n_comparisons, 1);
N_Group2 = zeros(n_comparisons, 1);
Mean_Group1 = zeros(n_comparisons, 1);
Mean_Group2 = zeros(n_comparisons, 1);
Mean_Difference = zeros(n_comparisons, 1);
Mean_Difference_CI_Lower = zeros(n_comparisons, 1);
Mean_Difference_CI_Upper = zeros(n_comparisons, 1);
T_Value = zeros(n_comparisons, 1);
Welch_DF = zeros(n_comparisons, 1);
P_Raw = zeros(n_comparisons, 1);
Cohen_d = zeros(n_comparisons, 1);
Hedges_g = zeros(n_comparisons, 1);
Hedges_g_CI_Lower = zeros(n_comparisons, 1);
Hedges_g_CI_Upper = zeros(n_comparisons, 1);

for k = 1:n_comparisons

    x = pad_groups{pair_index(k, 1)};
    y = pad_groups{pair_index(k, 2)};

    x = x(~isnan(x));
    y = y(~isnan(y));

    n1 = numel(x);
    n2 = numel(y);

    mean1 = mean(x);
    mean2 = mean(y);

    sd1 = std(x);
    sd2 = std(y);

    N_Group1(k) = n1;
    N_Group2(k) = n2;
    Mean_Group1(k) = mean1;
    Mean_Group2(k) = mean2;
    Mean_Difference(k) = mean1 - mean2;

    % Welch独立样本t检验
    [~, P_Raw(k), ci_diff, stats_t] = ttest2( ...
        x, ...
        y, ...
        'Vartype', 'unequal' ...
    );

    Mean_Difference_CI_Lower(k) = ci_diff(1);
    Mean_Difference_CI_Upper(k) = ci_diff(2);
    T_Value(k) = stats_t.tstat;
    Welch_DF(k) = stats_t.df;

    % 合并标准差
    pooled_sd = sqrt( ...
        ((n1 - 1) * sd1^2 + (n2 - 1) * sd2^2) / ...
        (n1 + n2 - 2) ...
    );

    if pooled_sd == 0
        Cohen_d(k) = NaN;
        Hedges_g(k) = NaN;
        Hedges_g_CI_Lower(k) = NaN;
        Hedges_g_CI_Upper(k) = NaN;
        continue;
    end

    % Cohen's d：第一组减第二组，保留方向
    Cohen_d(k) = (mean1 - mean2) / pooled_sd;

    % Hedges' g偏倚校正
    correction_J = 1 - 3 / (4 * (n1 + n2) - 9);
    Hedges_g(k) = correction_J * Cohen_d(k);

    % Hedges' g近似标准误和95%置信区间
    se_g = sqrt( ...
        (n1 + n2) / (n1 * n2) + ...
