% ABIDE脑龄预测、年龄偏倚校正、区域W-score相关及组间效应量分析
%
% 输入：
%   1. ABIDE_total2.xlsx
%      必须包含：SUB_ID、DX_GROUP、AGE_AT_SCAN、68个Volume变量
%
%   2. ABIDE_All_Metrics_Subtypes_Summaryx.xlsx
%      必须包含：SUB_ID、DX_GROUP、Volume_Subtype、Volume_01~Volume_68
%
% 输出：
%   1. GPR_Figure_A_Brain_Age_Prediction.png
%   2. GPR_Figure_C_Brain_PAD_Distributions.png
%   3. GPR_Brain_Age_Individual_Results.xlsx
%   4. GPR_ASD_All_ROI_PAD_Correlation_Wscore.xlsx
%   5. GPR_Brain_PAD_Group_Comparison_Effect_Sizes.xlsx
%
% 说明：
%   1. TDC模型性能采用嵌套五折交叉验证得到的折外预测。
%   2. ASD预测来自使用全部有效TDC训练的最终岭回归模型。
%   3. Brain-PAD在TDC折外预测结果中估计年龄偏倚，并对全部样本进行校正。
%   4. 图A显示未经年龄偏倚校正的预测年龄，以反映原始模型性能。
%   5. W-score相关、组间比较和图C均使用年龄偏倚校正后的Brain-PAD。
% ========================================================================

clear;
clc;
close all;

%% ========================= 0. 工作目录和参数 =========================
% ---- Repository paths (no edit needed if you keep this folder layout) ----
script_dir = fileparts(mfilename('fullpath'));
repo_root  = fileparts(script_dir);            % repository root
work_dir   = fullfile(repo_root, 'data');      % input tables + intermediate outputs
if ~exist(work_dir, 'dir'), mkdir(work_dir); end
cd(work_dir);

raw_file = 'ABIDE_total2.xlsx';
wscore_file = 'ABIDE_All_Metrics_Subtypes_Summaryx.xlsx';

rng_seed = 42;
outer_k = 5;
inner_k = 5;
lambda_list = logspace(-3, 3, 20);

fprintf('============================================================\n');
fprintf('开始执行ABIDE脑龄与Brain-PAD分析\n');
fprintf('工作目录：%s\n', work_dir);
fprintf('============================================================\n');

%% ========================= 1. 读取原始结构数据 =========================
if ~exist(raw_file, 'file')
    error('找不到文件：%s', raw_file);
end

fprintf('\n读取原始数据：%s\n', raw_file);
raw = readtable(raw_file);
raw.SUB_ID = string(raw.SUB_ID);

required_raw_vars = {'SUB_ID', 'DX_GROUP', 'AGE_AT_SCAN'};
for i = 1:numel(required_raw_vars)
    if ~ismember(required_raw_vars{i}, raw.Properties.VariableNames)
        error('原始数据缺少变量：%s', required_raw_vars{i});
    end
end

% 识别68个原始体积变量，同时排除可能存在的Subtype字段
all_raw_vars = raw.Properties.VariableNames;
vol_raw_cols = all_raw_vars( ...
    startsWith(all_raw_vars, 'Volume') & ...
    ~contains(all_raw_vars, 'Subtype', 'IgnoreCase', true) ...
);

if numel(vol_raw_cols) ~= 68
    error('原始体积列数不是68，实际为%d，请检查变量名称。', numel(vol_raw_cols));
end

X_raw = raw{:, vol_raw_cols};
y_age = raw.AGE_AT_SCAN;
dx = raw.DX_GROUP;

asd_idx = (dx == 1);
tdc_idx = (dx == 2);

valid_features = all(~isnan(X_raw), 2);
valid_age = ~isnan(y_age);

valid_asd = asd_idx & valid_features & valid_age;
valid_tdc = tdc_idx & valid_features & valid_age;

fprintf('总样本量：%d\n', height(raw));
fprintf('ASD总样本量：%d；有效预测样本量：%d\n', ...
    sum(asd_idx), sum(valid_asd));
fprintf('TDC总样本量：%d；有效建模样本量：%d\n', ...
    sum(tdc_idx), sum(valid_tdc));

%% ========================= 2. TDC嵌套交叉验证折外预测 =========================
fprintf('\n开始TDC嵌套%d折交叉验证...\n', outer_k);

X_tdc = X_raw(valid_tdc, :);
y_tdc = y_age(valid_tdc);

n_tdc = size(X_tdc, 1);
pred_tdc_oof = nan(n_tdc, 1);
outer_lambda = nan(outer_k, 1);

rng(rng_seed);
outer_cv = cvpartition(n_tdc, 'KFold', outer_k);

for fold = 1:outer_cv.NumTestSets

    outer_train_idx = outer_cv.training(fold);
    outer_test_idx = outer_cv.test(fold);

    X_outer_train = X_tdc(outer_train_idx, :);
    y_outer_train = y_tdc(outer_train_idx);

    X_outer_test = X_tdc(outer_test_idx, :);

    % GPR：超参数由 MLE 自动优化（无 lambda）
    best_lambda_fold = NaN;
    outer_lambda(fold) = NaN;

    % 仅使用当前外层训练集计算标准化参数
    mu_fold = mean(X_outer_train, 1);
    sigma_fold = std(X_outer_train, 0, 1);
    sigma_fold(sigma_fold == 0) = 1;

    X_outer_train_std = (X_outer_train - mu_fold) ./ sigma_fold;
    X_outer_test_std = (X_outer_test - mu_fold) ./ sigma_fold;

    model_fold = fitrgp( ...
        X_outer_train_std, ...
        y_outer_train, ...
        'KernelFunction', 'squaredexponential', ...
        'Standardize', false ...
    );

    pred_tdc_oof(outer_test_idx) = predict(model_fold, X_outer_test_std);

    fprintf('外层第%d折完成（GPR）\n', fold);
end

if any(isnan(pred_tdc_oof))
    error('TDC折外预测存在未生成的数值，请检查交叉验证流程。');
end

%% ========================= 3. 最终TDC模型及ASD预测 =========================
fprintf('\n使用全部有效TDC选择最终lambda并训练模型...\n');

lambda_final = NaN;
fprintf('最终模型：GPR（squaredexponential，超参数 MLE 自动优化）\n');

mu_final = mean(X_tdc, 1);
sigma_final = std(X_tdc, 0, 1);
sigma_final(sigma_final == 0) = 1;

X_tdc_std = (X_tdc - mu_final) ./ sigma_final;

final_model = fitrgp( ...
    X_tdc_std, ...
    y_tdc, ...
    'KernelFunction', 'squaredexponential', ...
    'Standardize', false ...
);

% 建立完整预测年龄向量
pred_age_raw = nan(height(raw), 1);

% TDC使用折外预测，避免训练集内性能偏高
pred_age_raw(valid_tdc) = pred_tdc_oof;

% ASD使用全部TDC训练的最终模型进行预测
X_asd = X_raw(valid_asd, :);
X_asd_std = (X_asd - mu_final) ./ sigma_final;
pred_age_raw(valid_asd) = predict(final_model, X_asd_std);

raw.Predicted_Age_Raw = pred_age_raw;
raw.PAD_Raw = raw.Predicted_Age_Raw - raw.AGE_AT_SCAN;

%% ========================= 4. Brain-PAD年龄偏倚校正 =========================
% 在TDC折外预测结果中拟合：原始PAD = 截距 + 斜率 × 年龄
tdc_age_bias = raw.AGE_AT_SCAN(valid_tdc);
tdc_pad_bias = raw.PAD_Raw(valid_tdc);

bias_coef = polyfit(tdc_age_bias, tdc_pad_bias, 1);
expected_bias_all = polyval(bias_coef, raw.AGE_AT_SCAN);

% 校正后的Brain-PAD
raw.PAD = raw.PAD_Raw - expected_bias_all;
raw.Predicted_Age_Corrected = raw.AGE_AT_SCAN + raw.PAD;

fprintf('\n年龄偏倚模型：PAD_raw = %.6f × Age + %.6f\n', ...
    bias_coef(1), bias_coef(2));

fprintf('校正前TDC PAD均值：%.4f年\n', ...
    mean(raw.PAD_Raw(valid_tdc), 'omitnan'));
fprintf('校正后TDC PAD均值：%.4f年\n', ...
    mean(raw.PAD(valid_tdc), 'omitnan'));

%% ========================= 5. 脑龄模型性能 =========================
metrics_asd = prediction_metrics( ...
    raw.AGE_AT_SCAN(valid_asd), ...
    raw.Predicted_Age_Raw(valid_asd) ...
);

metrics_tdc = prediction_metrics( ...
    raw.AGE_AT_SCAN(valid_tdc), ...
    raw.Predicted_Age_Raw(valid_tdc) ...
);

performance_table = table( ...
    ["ASD"; "TDC"], ...
    [metrics_asd.N; metrics_tdc.N], ...
    [metrics_asd.R; metrics_tdc.R], ...
    [metrics_asd.MAE; metrics_tdc.MAE], ...
    [metrics_asd.RMSE; metrics_tdc.RMSE], ...
    [metrics_asd.R2; metrics_tdc.R2], ...
    'VariableNames', { ...
        'Group', ...
        'N', ...
        'Correlation_R', ...
        'MAE_years', ...
        'RMSE_years', ...
        'R_squared' ...
    } ...
);

disp('脑龄预测模型性能：');
disp(performance_table);

%% ========================= 6. 图A：实际年龄与预测年龄 =========================
valid_plot = ...
